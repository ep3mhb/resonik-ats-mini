#!/usr/bin/env python3
"""Generate ats-mini/BrandBitmaps.h: the RESONIK wordmark as 8-bit alpha masks.

The wordmark is set in Sora SemiBold (600) with +7.5% letter spacing, as the
RESONIK brand guidelines specify. Usage: gen_brand.py path/to/Sora[wght].ttf
"""
import sys
from PIL import Image, ImageDraw, ImageFont

TEXT = "RESONIK"
TRACKING = 0.075          # +7.5% of the font size
WEIGHT = 600              # SemiBold

def render(font_path, cap_px):
    # Find the font size whose cap height ("R") is cap_px pixels
    size = cap_px
    for _ in range(40):
        f = ImageFont.truetype(font_path, size * 4)
        f.set_variation_by_axes([WEIGHT])
        b = f.getbbox("R")
        cap = (b[3] - b[1]) / 4
        if abs(cap - cap_px) < 0.05: break
        size *= cap_px / cap
    S = 4                              # supersample for clean anti-aliasing
    f = ImageFont.truetype(font_path, round(size * S))
    f.set_variation_by_axes([WEIGHT])
    ascent, _ = f.getmetrics()
    w = sum(f.getlength(c) for c in TEXT) + TRACKING * size * S * (len(TEXT) - 1)
    img = Image.new("L", (int(w) + 8 * S, int(ascent * 1.4)), 0)
    d = ImageDraw.Draw(img)
    x = 0
    for c in TEXT:
        d.text((x, 0), c, font=f, fill=255)
        x += f.getlength(c) + TRACKING * size * S
    img = img.crop(img.getbbox())
    img = img.resize((max(1, round(img.width / S)), max(1, round(img.height / S))), Image.LANCZOS)
    return img

def c_array(name, img):
    data = list(img.get_flattened_data()) if hasattr(img, "get_flattened_data") else list(img.getdata())
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    return (f"// {img.width}x{img.height}, 8-bit alpha\n"
            f"static const uint16_t {name}_W = {img.width};\n"
            f"static const uint16_t {name}_H = {img.height};\n"
            f"static const uint8_t {name}[] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n")

def main():
    font = sys.argv[1]
    big = render(font, 30)     # boot screen
    small = render(font, 13)   # About screen header
    out = ["// Generated by tools/gen_brand.py from Sora SemiBold. Do not edit.",
           "#ifndef BRAND_BITMAPS_H", "#define BRAND_BITMAPS_H", "", "#include <stdint.h>",
           "#ifndef PROGMEM", "#define PROGMEM", "#endif", "",
           c_array("WORDMARK_L", big), c_array("WORDMARK_S", small), "#endif // BRAND_BITMAPS_H", ""]
    open("ats-mini/BrandBitmaps.h", "w").write("\n".join(out))
    print("large", big.size, "small", small.size)

main()
