#!/usr/bin/env python3
"""Make an anti-aliased VLW font (LovyanGFX smooth font) as a C header.

Usage: gen_vlw.py <font.ttf> <pixel size> <C name> <out.h> [characters]
Default characters: printable ASCII. Glyph metrics follow the VLW layout that
LovyanGFX's VLWfont::loadFont() reads: 24-byte header, 28 bytes per glyph,
then the 8-bit alpha bitmaps in the same order, all integers big-endian.
"""
import struct
import sys
from PIL import Image, ImageDraw, ImageFont


def build(ttf, px, chars):
    font = ImageFont.truetype(ttf, px)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        adv = int(round(font.getlength(ch)))
        if ch == ' ':
            glyphs.append((ord(ch), 0, 0, adv, 0, 0, b''))
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
        w, h = x1 - x0, y1 - y0
        img = Image.new('L', (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
        glyphs.append((ord(ch), h, w, adv, -y0, x0, img.tobytes()))
    data = struct.pack('>6i', len(glyphs), 11, px, 0, ascent, descent)
    for (u, h, w, adv, dy, dx, _) in glyphs:
        data += struct.pack('>7i', u, h, w, adv, dy, dx, 0)
    for g in glyphs:
        data += g[6]
    return data


def main():
    ttf, px, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    chars = sys.argv[5] if len(sys.argv) > 5 else ''.join(chr(c) for c in range(32, 127))
    data = build(ttf, px, chars)
    with open(out, 'w') as f:
        f.write('// Generated by tools/gen_vlw.py from %s at %d px. Do not edit.\n' % (ttf.split('/')[-1], px))
        f.write('#pragma once\n#include <stdint.h>\n\n')
        f.write('static const uint8_t %s[%d] PROGMEM = {\n' % (name, len(data)))
        for i in range(0, len(data), 24):
            f.write('  ' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',\n')
        f.write('};\n')
    print(out, len(data), 'bytes')


if __name__ == '__main__':
    main()
